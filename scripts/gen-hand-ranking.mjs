// One-off generator: ranks the 169 starting hands by Monte Carlo equity vs one random hand.
// Writes src/engine/handRankingData.ts. Deterministic (seeded).
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';

const server = await createServer({ configFile: false, server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const { ALL_LABELS, labelCombos } = await server.ssrLoadModule('/src/engine/ranges.ts');
const { evaluate } = await server.ssrLoadModule('/src/engine/evaluator.ts');
const { createRng } = await server.ssrLoadModule('/src/engine/rng.ts');
const { fullDeck } = await server.ssrLoadModule('/src/engine/cards.ts');

const rng = createRng(2024);
const N = 60000;
const res = [];
for (const label of ALL_LABELS) {
  const hand = labelCombos(label)[0];
  const deck = fullDeck().filter((c) => c !== hand[0] && c !== hand[1]);
  let score = 0;
  for (let i = 0; i < N; i++) {
    // partial Fisher-Yates for 7 cards
    for (let k = 0; k < 7; k++) {
      const j = k + rng.int(deck.length - k);
      [deck[k], deck[j]] = [deck[j], deck[k]];
    }
    const opp = [deck[0], deck[1]];
    const board = deck.slice(2, 7);
    const a = evaluate([...hand, ...board]);
    const b = evaluate([...opp, ...board]);
    score += a > b ? 1 : a === b ? 0.5 : 0;
  }
  res.push({ label, eq: score / N });
}
res.sort((a, b) => b.eq - a.eq);
const body = `// GENERATED by scripts/gen-hand-ranking.mjs — do not edit by hand.
// The 169 starting hands ordered best to worst by equity against one random hand.
export const HAND_RANKING: readonly string[] = ${JSON.stringify(res.map((r) => r.label))};
export const HAND_EQUITY_VS_RANDOM: Readonly<Record<string, number>> = ${JSON.stringify(Object.fromEntries(res.map((r) => [r.label, Math.round(r.eq * 1000) / 1000])))};
`;
writeFileSync('src/engine/handRankingData.ts', body);
console.log(res.slice(0, 12).map((r) => `${r.label} ${r.eq.toFixed(3)}`).join(', '), '...', res.slice(-5).map((r) => `${r.label} ${r.eq.toFixed(3)}`).join(', '));
await server.close();
